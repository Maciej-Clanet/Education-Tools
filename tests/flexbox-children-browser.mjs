// Opt-in browser integration check. Use the isolated Chrome/local server setup
// in flexbox-browser.mjs. No npm dependencies; Node 22+.
import assert from 'node:assert/strict'
import { createBrowserSession } from './helpers/browser-session.mjs'

const lessonPath = '/pages/topics/flexbox-wrapping-and-children.html?context=web-development'
const { origin, send, ev, waitFor, load, click, input, text, boxes, near, screenshot, errors, close } = await createBrowserSession({
  lessonPath, readyExpression: "document.querySelectorAll('[data-flex-ready]').length === 13",
})
const childDisplay = id => ev(`getComputedStyle(document.querySelector('[data-flex-explorer="${id}"] [data-flex-child="2"]')).display`)
const reset = id => click(`[data-flex-explorer="${id}"] [data-flex-reset]`)
const nestedBoxes = () => ev("[...document.querySelectorAll('#nested .fi-grandchild')].map(e => { const r=e.getBoundingClientRect(); return {x:r.x,y:r.y}; })")

try {
  await send('Runtime.enable')
  await send('Page.enable')
  await send('Log.enable')
  await send('Emulation.setDeviceMetricsOverride', { width: 1366, height: 900, deviceScaleFactor: 1, mobile: false })
  await load()
  await ev('localStorage.clear()')
  await load()
  assert.equal(await ev("document.querySelectorAll('[data-lesson-section]').length"), 19)
  assert.equal(await ev("new Set([...document.querySelectorAll('[id]')].map(e => e.id)).size === document.querySelectorAll('[id]').length"), true)
  assert.deepEqual(await ev("[...document.querySelectorAll('[data-section-link]')].filter(a => !document.getElementById(a.hash.slice(1))).map(a => a.hash)"), [])
  assert.equal(await ev("document.body.textContent.includes('flex-basis')"), false)
  await ev("window.originalChildren = [...document.querySelectorAll('[data-flex-parent] > div')]")
  await screenshot('children-desktop')

  let b = await boxes('wrap')
  assert.equal(new Set(b.children.map(c => c.y)).size, 1)
  assert.ok(b.children.at(-1).x + 96 > b.parent.x + b.parent.width)
  // Use the native select with the keyboard.
  await ev("document.querySelector('#wrap-wrap').focus()")
  await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'ArrowDown', code: 'ArrowDown', windowsVirtualKeyCode: 40 })
  await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'ArrowDown', code: 'ArrowDown', windowsVirtualKeyCode: 40 })
  await waitFor("document.querySelector('#wrap-wrap').value === 'wrap'")
  b = await boxes('wrap')
  assert.equal(new Set(b.children.map(c => c.y)).size, 2)
  assert.ok(b.children[2].y > b.children[0].y)
  near(b.children[2].x, b.children[0].x, 'wrapped line starts at same edge')
  near(b.children[2].y - b.children[0].y - 48, 8, 'gap between lines')
  await input('#reflow-parentWidth', 160)
  b = await boxes('reflow')
  assert.equal(new Set(b.children.map(c => c.y)).size, 4)
  await input('#reflow-parentWidth', 420)
  b = await boxes('reflow')
  assert.equal(new Set(b.children.map(c => c.y)).size, 1)
  b.children.forEach(c => near(c.width, 96, 'wrap does not change minimum card width'))

  assert.equal(await childDisplay('nested'), 'block')
  let inner = await nestedBoxes()
  assert.ok(inner[1].y > inner[0].y)
  await input('#nested-innerDisplay', 'flex')
  inner = await nestedBoxes()
  near(inner[0].y, inner[1].y, 'inner display flex creates a row')
  assert.ok(inner[1].x > inner[0].x)
  assert.equal(await childDisplay('nested'), 'flex')
  b = await boxes('nested')
  near(b.children[0].y, b.children[2].y, 'outer siblings retain their row')
  await reset('nested')
  assert.equal(await childDisplay('nested'), 'block')

  b = await boxes('grow')
  b.children.forEach(c => near(c.width, 64, 'no default growth'))
  await input('#grow-grow', 1)
  b = await boxes('grow')
  near(b.children[0].width, 64, 'first child does not grow')
  near(b.children[2].width, 64, 'third child does not grow')
  near(b.children[1].width, b.parent.width - 4 - 16 - 128, 'one child takes spare space')
  assert.equal(await childDisplay('grow'), 'block', 'growth never sets display flex')
  await input('#shares-grow', 2)
  b = await boxes('shares')
  near(b.children[1].width - 64, 2 * (b.children[0].width - 64), 'grow 2 gets twice the addition')
  assert.ok(b.children[1].width < 2 * b.children[0].width, 'final width is not doubled')

  b = await boxes('shrink')
  b.children.forEach(c => near(c.width, 120, 'requested widths fit roomy parent'))
  await input('#shrink-parentWidth', 240)
  b = await boxes('shrink')
  b.children.forEach(c => near(c.width, (b.parent.width - 4 - 16) / 3, 'default equal shrink'))
  assert.equal(new Set(b.children.map(c => c.y)).size, 1)
  await input('#protect-shrink', 0)
  b = await boxes('protect')
  near(b.children[1].width, 120, 'shrink zero protects one width')
  near(b.children[0].width, b.children[2].width, 'others share shortage')
  assert.ok(b.children[0].width < 120)
  await input('#refuse-shrink', 0)
  b = await boxes('refuse')
  b.children.forEach(c => near(c.width, 120, 'all refuse shrink'))
  assert.ok(b.children[2].x + 120 > b.parent.x + b.parent.width)
  assert.equal(await ev('document.documentElement.scrollWidth <= innerWidth'), true, 'overflow stays in diagram')
  assert.match(await text('[data-flex-explorer=refuse] [data-flex-measurements]'), /extend beyond/)

  b = await boxes('presets')
  assert.ok(b.children[0].width > 120, 'flex auto grows')
  await input('#presets-parentWidth', 240)
  b = await boxes('presets')
  assert.ok(b.children[0].width < 120, 'flex auto shrinks')
  await input('#presets-preset', 'none')
  b = await boxes('presets')
  b.children.forEach(c => near(c.width, 120, 'flex none is inflexible'))
  await input('#presets-parentWidth', 420)
  b = await boxes('presets')
  b.children.forEach(c => near(c.width, 120, 'flex none does not grow'))
  await reset('presets')
  b = await boxes('presets')
  assert.ok(b.children[0].width > 120, 'reset clears stale shrink/grow shorthand state')
  b = await boxes('shorthand')
  near(b.children[1].width - b.children[0].width, 80, 'auto preserves starting width difference in roomy parent')
  await input('#shorthand-preset', '1')
  b = await boxes('shorthand')
  near(b.children[0].width, b.children[1].width, 'flex 1 equal sharing')
  near(b.children[1].width, b.children[2].width, 'all three equal')
  assert.equal(await childDisplay('shorthand'), 'block', 'shorthand does not set display flex')
  await reset('shorthand')
  b = await boxes('shorthand')
  near(b.children[1].width - b.children[0].width, 80, 'reset restores auto size behaviour')

  await input('#self-self', 'center')
  b = await boxes('self')
  near(b.children[1].y + b.children[1].height / 2, b.parent.y + b.parent.height / 2, 'self centres child two vertically')
  near(b.children[0].y, b.parent.y + 2, 'self does not move sibling')
  near(b.children[2].y, b.parent.y + 2, 'self does not move other sibling')
  await input('#self-self', 'flex-end')
  b = await boxes('self')
  near(b.children[1].y + b.children[1].height, b.parent.y + b.parent.height - 2, 'self end')
  await input('#self-self', 'stretch')
  b = await boxes('self')
  near(b.children[1].height, b.parent.height - 4, 'only auto-sized child stretches')
  near(b.children[0].height, 48, 'sibling not stretched')
  await input('#self-self', 'auto')
  b = await boxes('self')
  near(b.children[1].y, b.children[0].y, 'auto follows parent start')
  near(b.children[1].height, 48, 'auto removes explicit stretch')
  await input('#self-turn-direction', 'column')
  b = await boxes('self-turn')
  near(b.children[1].x + 24, b.parent.x + b.parent.width / 2, 'column self follows horizontal cross axis')
  near(b.children[0].x, b.parent.x + 2, 'column sibling starts at left')
  assert.ok(b.children[1].y > b.children[0].y && b.children[2].y > b.children[1].y)
  assert.match(await text('[data-flex-explorer=self-turn] [data-flex-horizontal]'), /Cross axis/)
  await input('#wrap-grow-grow', 1)
  b = await boxes('wrap-grow')
  near(b.children[0].y, b.children[2].y, 'first three on first line')
  assert.ok(b.children[3].y > b.children[0].y)
  near(b.children[3].width, b.parent.width - 4, 'lone last child fills its own line')
  assert.equal(await ev("[...document.querySelectorAll('[data-flex-parent] > div')].every((node, i) => node === window.originalChildren[i])"), true)

  await click('.live-code__primary-action')
  await ev("(() => { const e = document.querySelector('.live-code__editor'); e.value = e.value.replace('flex-wrap: nowrap', 'flex-wrap: wrap').replace('flex: none', 'flex: auto'); e.dispatchEvent(new Event('input', {bubbles:true})); })()")
  await waitFor("document.querySelector('.live-code__iframe').srcdoc.includes('flex-wrap: wrap') && document.querySelector('.live-code__iframe').srcdoc.includes('flex: auto')")
  assert.equal(await ev("document.querySelector('.live-code__iframe').getAttribute('sandbox')"), '')

  await click('[name=q3][value=a]')
  await ev("document.querySelector('#lesson-quiz').requestSubmit()")
  assert.match(await text('[data-question=q3] [data-question-feedback]'), /does not automatically/)
  await ev("for (const q of document.querySelectorAll('[data-question]')) q.querySelector('input[value=' + q.dataset.answer + ']').click(); document.querySelector('#lesson-quiz').requestSubmit(); const answer = document.querySelector('[data-exam-response]'); answer.value = 'The child needs its own display: flex to arrange A and B.'; answer.dispatchEvent(new Event('input', {bubbles:true}));")
  assert.equal(await ev("document.querySelectorAll('.quiz-question.is-correct').length"), 12)
  await load()
  assert.equal(await ev("document.querySelectorAll('[data-question] input:checked').length"), 12)
  assert.match(await ev("document.querySelector('[data-exam-response]').value"), /its own display/)
  const metadata = await ev("(async () => { const {catalogItems} = await import('/javascript/data/course-catalog.js'); const {webDevelopmentProgressData} = await import('/javascript/data/unit-progress-data.js'); const {readLessonQuizProgress} = await import('/javascript/core/quiz-progress.js'); return {catalog: catalogItems.find(x => x.id === 'topic-flexbox-wrapping-and-children'), quiz: webDevelopmentProgressData.sections.find(x => x.id === 'css-basics').lessons.find(x => x.id === 'flexbox-wrapping-and-children').quiz, summary: readLessonQuizProgress('flexbox-wrapping-and-children')}; })()")
  assert.equal(metadata.catalog.status, 'live')
  assert.deepEqual(metadata.quiz, {version: 1, totalQuestions: 12, passScore: 10})
  assert.equal(metadata.summary.correct, 12)
  assert.equal(metadata.summary.totalQuestions, 12)
  await load('/pages/resources/web-development.html', "document.querySelector('a[href*=\"flexbox-wrapping-and-children\"]')")
  assert.equal(await ev("document.querySelectorAll('#css-basics .lesson-item--live').length"), 9)
  assert.match(await text('#css-basics .topic-status'), /9 live/)
  await load('/pages/topics/flexbox-basics.html?context=web-development', "document.querySelector('[data-role=lesson-sequence] a[href*=\"flexbox-wrapping-and-children\"]')")
  await load()
  assert.ok(await ev("document.querySelector('[data-role=lesson-sequence] a[href*=\"flexbox-basics\"]') !== null"))
  await click('[data-action=reset-quiz]')
  assert.equal(await ev("document.querySelectorAll('[data-question] input:checked').length"), 0)

  for (const width of [390, 320]) {
    await send('Emulation.setDeviceMetricsOverride', {width, height: 844, deviceScaleFactor: 1, mobile: false})
    await input('#refuse-shrink', 0)
    await input('#presets-preset', 'none')
    assert.equal(await ev('document.documentElement.scrollWidth <= innerWidth'), true, `page contains overflow at ${width}`)
    const scrollable = await ev("(() => { const r = document.querySelector('[data-flex-explorer=refuse] .flex-explorer__viewport'); r.scrollLeft=100; return r.scrollLeft > 0 && r.tabIndex === 0; })()")
    assert.equal(scrollable, true, 'overflow can be scrolled in a focusable region')
    await ev("document.querySelector('#align-self').scrollIntoView()")
    await screenshot(`children-mobile-${width}`)
  }
  await send('Emulation.setDeviceMetricsOverride', {width: 1366, height: 900, deviceScaleFactor: 1, mobile: false})
  await click('[data-action=toggle-teacher-mode]')
  await waitFor("document.body.classList.contains('teacher-mode-active') && location.hash.endsWith('--opener')")
  assert.match(await ev('location.hash'), /--opener/)
  const slides=[]
  for (let index=0; index<70; index++) {
    const id=await ev('location.hash.slice(1)')
    slides.push(await text('[data-role=slide-status]'))
    if (id==='self-turn') await input('#self-turn-direction', 'column')
    if (['nested','grow-shares','shrink','flex-presets','flex-one','align-self','self-turn','wrap-grow','live-code'].includes(id)) await screenshot(`children-slide-${id}`)
    if (await ev("document.querySelector('[data-action=next-slide]').disabled")) break
    await click('[data-action=next-slide]')
  }
  assert.ok(slides.length >= 25 && slides.length < 70)
  await click('[data-action=exit-teacher-mode]')
  assert.equal(await ev("document.body.classList.contains('teacher-mode-active')"), false)
  assert.deepEqual(errors, [], 'no page errors')

  await send('Emulation.setScriptExecutionDisabled', {value:true})
  await send('Page.navigate', {url:origin+lessonPath})
  await new Promise(resolve=>setTimeout(resolve,500))
  await send('Emulation.setScriptExecutionDisabled', {value:false})
  assert.equal(await ev("document.querySelectorAll('[data-flex-ready]').length"), 0)
  assert.equal(await ev("document.querySelectorAll('[data-flex-parent]').length"), 13)
  assert.equal(await ev("document.querySelectorAll('[data-lesson-section]').length"), 19)
  assert.equal(await ev("document.querySelector('#wrap-wrap').disabled"), true)
  console.log(`PASS: wrapping, parent/child roles, grow shares, shrinking/overflow, flex presets/reset, self alignment, line growth, keyboard, code editing, persistence, hub/navigation, 320/390px, ${slides.length} slides, static fallback.`)
} finally {
  await close()
}
